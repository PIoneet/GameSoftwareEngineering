# ────────────────────────────────────────────────────────────
#  sRGB → 선형 변환
# ────────────────────────────────────────────────────────────
#
# 아래 색은 전부 sRGB(눈에 보이는 값)로 적는다. 하지만 Blender 의 Base Color 와
# glTF 의 baseColorFactor 는 **선형(linear)** 을 받는다. 그냥 넣으면 실제보다
# 밝고 바랜 색이 나온다. 그래서 넣기 직전에 반드시 변환한다.


def srgb_to_linear(c):
	"""sRGB 성분 하나를 선형으로."""
	if c <= 0.04045:
		return c / 12.92

	return ((c + 0.055) / 1.055) ** 2.4


def lin(rgb):
	"""sRGB 삼원색 튜플을 선형 RGBA 로. Blender/glTF 에 넣을 때 쓴다."""
	r, g, b = rgb

	return (srgb_to_linear(r), srgb_to_linear(g), srgb_to_linear(b), 1.0)


def hex_to_rgb(h):
	"""'#4a4238' → (0.290, 0.259, 0.220) sRGB."""
	h = h.lstrip('#')

	return (int(h[0:2], 16) / 255.0,
	        int(h[2:4], 16) / 255.0,
	        int(h[4:6], 16) / 255.0)


def mix(a, b, t):
	"""sRGB 공간에서 선형 보간. 변주색을 만들 때 쓴다."""
	return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


def shade(rgb, k):
	"""명도만 비율로 조절. k < 1 이면 어둡게, > 1 이면 밝게."""
	return tuple(min(1.0, max(0.0, rgb[i] * k)) for i in range(3))


def jitter(rgb, amount, rng):
	"""기준색을 **어두운 쪽으로만** 흔든다. 채널마다 따로 흔들어 색조도 조금 움직인다.

	왜 어두운 쪽뿐인가 — 이 색은 정점 색(COLOR_0)으로 나가는데, glTF 에서
	COLOR_0 은 baseColorFactor 에 **곱해지는 배율**이고 정규화 정수라 1.0 을 넘지 못한다.
	그래서 머티리얼 색이 "가장 밝은 기준" 이고 정점 색은 거기서 깎는 역할만 한다.
	밝게 흔들면 내보낼 때 1.0 에서 잘려 변주가 사라진다.
	"""
	return tuple(c * (1.0 - rng.uniform(0.0, amount)) for c in rgb)


